package com.sundry.order;

import com.sundry.catalog.ProductType;

import java.math.BigDecimal;

public class OrderItem {

    private Long id;
    private Long orderId;
    private Long productId;
    private String productName;
    private ProductType productType;
    private BigDecimal price;
    private Integer quantity;
    private String coverUrl;
    private Long digitalFileId;

    public Long getId() {
        return id;
    }

    public void setId(Long id) {
        this.id = id;
    }

    public Long getOrderId() {
        return orderId;
    }

    public void setOrderId(Long orderId) {
        this.orderId = orderId;
    }

    public Long getProductId() {
        return productId;
    }

    public void setProductId(Long productId) {
        this.productId = productId;
    }

    public String getProductName() {
        return productName;
    }

    public void setProductName(String productName) {
        this.productName = productName;
    }

    public ProductType getProductType() {
        return productType;
    }

    public void setProductType(ProductType productType) {
        this.productType = productType;
    }

    public BigDecimal getPrice() {
        return price;
    }

    public void setPrice(BigDecimal price) {
        this.price = price;
    }

    public Integer getQuantity() {
        return quantity;
    }

    public void setQuantity(Integer quantity) {
        this.quantity = quantity;
    }

    public String getCoverUrl() {
        return coverUrl;
    }

    public void setCoverUrl(String coverUrl) {
        this.coverUrl = coverUrl;
    }

    public Long getDigitalFileId() {
        return digitalFileId;
    }

    public void setDigitalFileId(Long digitalFileId) {
        this.digitalFileId = digitalFileId;
    }
}
